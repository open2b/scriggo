// differentialValue is the value shown in the templates of
// TestLexerJSContextsAgainstHTMLTemplate. Go's html/template escapes it
// differently in each context, so the context can be determined from the
// output. Its escaped forms do not occur in the generated code.
type differentialValue struct{}

func (differentialValue) String() string { return "a'\"\\/$`{<" }

// differentialData is the data of the Go templates.
type differentialData struct {
	V  differentialValue
	C  bool
	Xs []int
}

// differentialFragments are pieces of JavaScript code. The test generates
// the templates by combining them.
//
// "n-->0" is not included because Go's html/template treats "-->" as a
// comment also in the middle of a line, while Scriggo treats it as an
// operator.
var differentialFragments = []string{
	"x = ", "'a'", "\"a\"", "`a`", "`a${b}c`", "`${ `b` }`", "`${ '}' }`", "`It's`",
	"`${ {b: 1} }`", "`${ /}/.test(b) }`",
	"/a/", "/'/", "/[/]/", "/\"/", "a / b", "(a) / b", "a++ /", "a--", "a]",
	"return /'/.test(x);", "typeof", "a ? /b/ : c", "{}", "{ a }", "a\n", "1", "x.y",
	"'\\\\'", "\"\\\\\"", "// it's\n", "/* it's */", "<!-- it's\n",
	"{% if c %}'a'{% else %}\"b\"{% end %}", "{% if c %}a{% else %}(b){% end %}",
	"{% for x in xs %}a;{% end %}",
	"a\u00a0", "x =\u00a0", "typeof\u00a0", "a\u000b", "// it's\u2028",
}

// differentialSuffixes contain the shown value, and are appended to the
// combined fragments.
var differentialSuffixes = []string{
	"{{ v }}", "'{{ v }}'", "\"{{ v }}\"", "`{{ v }}`", "/{{ v }}/", "`${ {{ v }} }`",
}

// differentialScriggoErrors are the syntax errors that Scriggo reports, by
// prudence, for templates that Go's html/template accepts or rejects.
var differentialScriggoErrors = []string{
	"'/' could start a division or a regular expression",
}

// differentialUnclosedError is the syntax error that Scriggo reports when a
// script ends in a string, a template literal, a regular expression or a
// comment. Go's html/template reports an ErrEndContext error in this case.
const differentialUnclosedError = "unclosed JavaScript "

// TestLexerJSContextsAgainstHTMLTemplate tests that, in JavaScript code, the
// lexer determines the same context for a shown value as Go's
// html/template, for templates generated by combining fragments of
// JavaScript code.
func TestLexerJSContextsAgainstHTMLTemplate(t *testing.T) {

	toGo := strings.NewReplacer("{{ v }}", "{{.V}}", "{% if c %}", "{{if .C}}",
		"{% else %}", "{{else}}", "{% end %}", "{{end}}", "{% for x in xs %}", "{{range .Xs}}")
	render := func(src string) (string, error) {
		tmpl, err := template.New("t").Parse(src)
		if err != nil {
			return "", err
		}
		var b bytes.Buffer
		err = tmpl.Execute(&b, differentialData{C: true, Xs: []int{1}})
		return b.String(), err
	}

	// Determine how Go's html/template escapes the value in each context.
	encodings := map[ast.Context][]string{}
	for _, c := range []struct {
		ctx             ast.Context
		prefix, postfix string
	}{
		{ast.ContextJS, "<script>", "</script>"},
		{ast.ContextJSString, "<script>'", "'</script>"},
		{ast.ContextJSString, "<script>\"", "\"</script>"},
		{ast.ContextJSString, "<script>`", "`</script>"},
		{ast.ContextJSRegExp, "<script>/", "/</script>"},
		{ast.ContextHTML, "<p>", "</p>"},
	} {
		out, err := render(c.prefix + "{{.V}}" + c.postfix)
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(out, c.prefix) || !strings.HasSuffix(out, c.postfix) {
			t.Fatalf("unexpected output %q of Go's html/template", out)
		}
		encodings[c.ctx] = append(encodings[c.ctx], out[len(c.prefix):len(out)-len(c.postfix)])
	}
	// goContext returns the context of the value in the output of Go's
	// html/template, and false if it cannot be determined.
	goContext := func(out string) (ast.Context, bool) {
		var ctx ast.Context
		found := false
		for c, encs := range encodings {
			for _, enc := range encs {
				if strings.Contains(out, enc) {
					if found && c != ctx {
						return 0, false
					}
					ctx = c
					found = true
				}
			}
		}
		return ctx, found
	}

	var sources []string
	pieces := append([]string{""}, differentialFragments...)
	for _, a := range pieces {
		for _, b := range pieces {
			if a == "" && b != "" {
				continue
			}
			for _, s := range differentialSuffixes {
				// After a template literal, Go's html/template treats '/' as
				// the start of a regular expression, while it is a division.
				next := b
				if b == "" || isDifferentialComment(b) {
					next = s
				}
				if strings.HasSuffix(a, "`") && strings.HasPrefix(next, "/") ||
					strings.HasSuffix(b, "`") && strings.HasPrefix(s, "/") {
					continue
				}
				sources = append(sources, "<script>"+a+" "+b+" "+s+"</script>")
			}
		}
	}

	compared := map[ast.Context]int{}
	prudentErrors := 0
	for _, src := range sources {
		lex := scanTemplate([]byte(src), ast.FormatHTML, false)
		var ctx ast.Context
		shows := 0
		for tok := range lex.Tokens() {
			if tok.typ == tokenLeftBraces {
				ctx = tok.ctx
				shows++
			}
		}
		if lex.err == nil && shows != 1 {
			t.Errorf("source %q: expecting one shown value, got %d", src, shows)
			continue
		}
		out, goErr := render(toGo.Replace(src))
		switch {
		case lex.err != nil:
			// Scriggo can report an error also where Go's html/template does
			// not, but only by prudence. If the script ends in a string, a
			// regular expression or a comment, both report an error.
			if goErr == nil {
				prudentErrors++
			}
			var tmplErr *template.Error
			if strings.Contains(lex.err.Error(), differentialUnclosedError) {
				if !errors.As(goErr, &tmplErr) || tmplErr.ErrorCode != template.ErrEndContext {
					t.Errorf("source %q: unexpected error %q, Go's html/template reports %v", src, lex.err, goErr)
				}
			} else if !containsAny(lex.err.Error(), differentialScriggoErrors) {
				t.Errorf("source %q: unexpected error %q", src, lex.err)
			}
		case goErr != nil:
			// Where Go's html/template reports an error, such as a '/' that
			// is ambiguous or a script that does not end in code, Scriggo
			// must report an error too, otherwise it has guessed.
			t.Errorf("source %q: no error, Go's html/template reports %q", src, goErr)
		default:
			goCtx, ok := goContext(out)
			if !ok {
				t.Errorf("source %q: cannot determine the context of Go's html/template from %q", src, out)
			} else if ctx != goCtx {
				t.Errorf("source %q: value shown in %s context, Go's html/template shows it in %s context", src, ctx, goCtx)
			} else {
				compared[ctx]++
			}
		}
	}

	// Check that a change of the fragments does not reduce the coverage
	// significantly, and limit the errors that Scriggo reports by prudence.
	for ctx, min := range map[ast.Context]int{ast.ContextJS: 1500, ast.ContextJSString: 1800, ast.ContextJSRegExp: 140} {
		if compared[ctx] < min {
			t.Errorf("expecting at least %d compared values in %s context, got %d", min, ctx, compared[ctx])
		}
	}
	if prudentErrors > 10 {
		t.Errorf("expecting at most 10 errors where Go's html/template reports none, got %d", prudentErrors)
	}
}

// isDifferentialComment reports whether the fragment f is a comment.
func isDifferentialComment(f string) bool {
	return strings.HasPrefix(f, "//") || strings.HasPrefix(f, "/*") || strings.HasPrefix(f, "<!--")
}

// containsAny reports whether s contains any of the strings in subs.
func containsAny(s string, subs []string) bool {
	for _, sub := range subs {
		if strings.Contains(s, sub) {
			return true
		}
	}
	return false
}
